/** The icon of a group. One the app does not offer, such as Frigate's default `generic`, gets a plain grid. */
@Composable
fun groupIcon(name: String): ImageVector = knownGroupIcon(name) ?: Symbols.GridView

/** `null` for an icon the app does not offer, which nothing could tell apart from another. */
@Composable
fun knownGroupIcon(name: String): ImageVector? = icons[name]?.let { ImageVector.vectorResource(it.image) }

/** The readable name of an icon; one the app does not offer is only called the current one. */
internal fun groupIconLabel(name: String): Int = icons[name]?.label ?: R.string.group_icon_current
